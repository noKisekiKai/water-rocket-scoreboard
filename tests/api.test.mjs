import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://127.0.0.1:8787';
const password=crypto.randomUUID();
const api=async(path='',body,auth=password)=>{
 const r=await fetch(base+'/api/rooms'+path,{method:body?'POST':'GET',headers:{'Content-Type':'application/json',Authorization:'Bearer '+auth},body:body?JSON.stringify(body):undefined});
 return {status:r.status,data:await r.json()};
};
const created=await api('',{action:'create',title:'自動測試活動',password});assert.equal(created.status,201,JSON.stringify(created));
const eventId=created.data.event.id;
const write=async(operations)=>api('',{action:'write',eventId,operations});
const group={id:'g1',kind:'group',expectedVersion:0,opId:crypto.randomUUID(),data:{number:1,school:'測試學校'}};
assert.equal((await write([group])).data.outcomes[0].ok,true);
assert.equal((await write([group])).data.outcomes[0].ok,true,'Retry must be idempotent');
assert.equal((await api('?event='+eventId)).data.records.length,1);
const student={id:'s1',kind:'student',expectedVersion:0,opId:crypto.randomUUID(),data:{name:'測試學生',groupId:'g1',present:true}};
assert.equal((await write([student])).data.outcomes[0].ok,true);
const a={...student,expectedVersion:1,opId:crypto.randomUUID(),data:{...student.data,present:false}};
const b={...student,expectedVersion:1,opId:crypto.randomUUID(),data:{...student.data,name:'另一修改'}};
const results=await Promise.all([write([a]),write([b])]);assert.equal(results.filter(r=>r.data.outcomes[0].ok).length,1,'Only one concurrent version may win');
const shot={id:'a1',kind:'attempt',expectedVersion:0,opId:crypto.randomUUID(),data:{groupId:'g1',round:1,hit:true,score:0,distance:0,participants:[{id:'s1',name:'測試學生'}]}};
assert.equal((await write([shot])).data.outcomes[0].ok,true);
let data=(await api('?event='+eventId)).data;let saved=data.records.find(r=>r.id==='a1');assert.equal(saved.data.score,0);assert.equal(saved.data.distance,0);
assert.equal((await api('?event='+eventId,undefined,'wrong')).status,401);
assert.equal((await api('',{action:'write',eventId,operations:[{...shot,id:'bad',opId:crypto.randomUUID(),data:{...shot.data,hit:null}}]})).status,400);
const deleted={...shot,expectedVersion:1,opId:crypto.randomUUID(),data:{...shot.data,deleted:true}};assert.equal((await write([deleted])).data.outcomes[0].ok,true);
data=(await api('?event='+eventId)).data;assert.equal(data.records.find(r=>r.id==='a1').data.deleted,true);
assert.equal(data.records.find(r=>r.id==='a1').data.participants[0].name,'測試學生');
console.log('PASS: create/join, password protection, durable read, retry idempotency, concurrent conflict, zero scores, validation, soft deletion, participant snapshots');
console.log('TEST_EVENT='+eventId);
